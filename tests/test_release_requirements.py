"""The release's hash-pinned requirements file (scripts/release_requirements.py; the founder's README changes, item 7).
ci.yml installs a built wheel through one, with --require-hashes, in a fresh environment: this holds its form."""
from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

spec = importlib.util.spec_from_file_location(
    "release_requirements", Path(__file__).resolve().parents[1] / "scripts" / "release_requirements.py")
rr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(rr)

EXPORTED = """# This file was autogenerated by uv via the following command:
#    uv export --format requirements-txt --frozen --extra aws --no-dev --no-emit-project
boto3==1.43.118 \\
    --hash=sha256:ab8f3d2c622ef039338b4f228d97ea55f1abd573d84bb9b9a5ee8cb6780c0ccd \\
    --hash=sha256:c0620f799e0f0c222ba42c337b65cdbcd3da38a3121187f634d8926cbbb28a9c
    # via arvaken-stop-test
"""
WHEEL = "arvaken_stop_test-0.2.0-py3-none-any.whl"


def test_the_file_names_the_wheel_by_its_address_and_hash_then_every_package_by_its_hashes():
    text = rr.requirements("0.2.0", WHEEL, "a" * 64, EXPORTED)
    lines = text.splitlines()
    assert lines[2] == f"arvaken-stop-test[aws] @ {rr.RELEASES}/v0.2.0/{WHEEL} \\"
    assert lines[3] == "    --hash=sha256:" + "a" * 64
    assert "boto3==1.43.118 \\" in lines and text.count("--hash=sha256:") == 3
    assert "# via" not in text and text.endswith("\n")


@pytest.mark.parametrize(("version", "wheel", "digest", "exported", "said"), [
    ("0.2.0", WHEEL, "short", EXPORTED, "64 hexadecimal"),
    ("0.3.0", WHEEL, "a" * 64, EXPORTED, "not version 0.3.0's wheel"),
    ("0.2.0", WHEEL, "a" * 64, "boto3==1.43.118\n", "hold no hashes"),
])
def test_a_file_that_would_not_pin_every_byte_is_refused(version, wheel, digest, exported, said):
    with pytest.raises(ValueError, match=said):
        rr.requirements(version, wheel, digest, exported)


PROBE = "arvaken_stop_test_probe-0.5.0-py3-none-any.whl"


def test_the_probes_file_names_its_one_wheel_by_its_address_and_hash():
    """The README's "Add the probe" (the founder, 18:06:47 UTC on 2 November 2026) installs it with --no-deps."""
    assert rr.probe_requirements("0.5.0", PROBE, "b" * 64) == (
        f"arvaken-stop-test-probe @ {rr.RELEASES}/v0.5.0/{PROBE} \\\n    --hash=sha256:" + "b" * 64 + "\n")
    with pytest.raises(ValueError, match="64 hexadecimal"):
        rr.probe_requirements("0.5.0", PROBE, "short")
    with pytest.raises(ValueError, match="not the probe's version 0.6.0 wheel"):
        rr.probe_requirements("0.6.0", PROBE, "b" * 64)
    with pytest.raises(ValueError, match="not the probe's"):
        rr.probe_requirements("0.5.0", WHEEL, "b" * 64)


def test_a_release_builds_checks_hashes_and_signs_the_probe_as_the_readme_installs_it():
    root = Path(__file__).resolve().parents[1]
    release = (root / ".github" / "workflows" / "release.yml").read_text(encoding="utf-8")
    readme = (root / "README.md").read_text(encoding="utf-8")
    assert "uv build probe --out-dir dist" in release
    assert 'test "$probe" = "$version"' in release                   # the probe's version is the tag's
    assert '> "dist/probe-requirements-$version.txt"' in release
    assert "requirements-*.txt probe-requirements-*.txt | tee SHA256SUMS" in release
    assert "./kit/dist/probe-requirements-*.txt" in release           # signed with the other files
    assert "-r probe-requirements-0.5.0.txt" in readme and "--no-deps --target" in readme

